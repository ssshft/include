#pragma once

// SpinBackoff.h
// 自旋让步与退避 —— **不依赖共享内存、不依赖任何队列**。
// 任何 "while 轮询、失败就重试" 的循环都可以用。
//
// ---------------------------------------------------------------------------
// 三个函数，别混用
// ---------------------------------------------------------------------------
//   cpu_relax()         一条 CPU 让步指令。**无状态、无策略** —— 不自增计数器、
//                       不 yield、不睡。给"确定马上有活要干、只想别把前端执行
//                       端口占死"的循环：排空一个本地缓冲。
//   backoff(step)       阶梯。给"等对端进程的 μs 级事件"的热路径：
//                       报单 / 回报 / 行情。
//   backoff_sleep(step) 阶梯 + 阶梯走完后的低频睡眠。只给"低频**且**不独占核"
//                       的通道。
//
//   step 由调用方持有；**拿到数据的那一轮必须归零**，否则永远停在最高档。
//
// ---------------------------------------------------------------------------
// 用法
// ---------------------------------------------------------------------------
//   unsigned step = 0;
//   while (running) {
//       bool idle = true;
//       if (q1.pop(a)) { handle(a); idle = false; }   // 任一队列有活就算"不空"
//       if (q2.pop(b)) { handle(b); idle = false; }
//       if (idle) spin::backoff(step);
//       else      step = 0;
//   }
//
// 为什么这么选、每个循环具体用哪个，见 docs/队列使用方式.md §6.4 与
// docs/全系统性能与延迟审查.md 的 P0-5。

#include <chrono>
#include <thread>

namespace spin {

// ---------------------------------------------------------------------------
// CPU 让步原语：无状态、无策略
// ---------------------------------------------------------------------------
// 一条"我在自旋"的提示指令，只做两件事：
//   1. 让出前端执行端口，减少对 SMT 兄弟核的挤占；
//   2. 消除退出自旋时的 memory-order-violation / 分支预测失败惩罚
//      —— 这才是 PAUSE 比空循环快的真正原因，不是"省电"。
//
// x86 上就是一条 pause（~10-140 周期）。非 x86 走 yield 或空操作。
//
// 仓库里原本有四份各自独立的 pause 写法（oms/OmsShm.h:716、notify_ring.h:32、
// BeastRestClient.h:63、以及 ShmQueueCommon.h 里那份），都应当收敛到这里。
inline void cpu_relax() noexcept {
#if defined(__x86_64__) || defined(__i386__)
    __builtin_ia32_pause();
#elif defined(__aarch64__)
    asm volatile("yield" ::: "memory");
#endif
}

// ---------------------------------------------------------------------------
// 退避阶梯：等对端进程事件时的策略
// ---------------------------------------------------------------------------
//   前 8 次：立刻重试（低延迟场景下下一条消息通常马上就到）
//   8..63 ：发 CPU pause，降低自旋对同核的干扰
//   64+   ：std::this_thread::yield()，把时间片让给生产者
//
// **刻意不含 sleep**：给低延迟通道加睡眠会引入不可控的额外延迟。
// 低频通道用 backoff_sleep()。
//
// 消费者紧密自旋时生产者实测会被拖慢数倍（共享内存队列上比锁队列更明显，
// 因为读写落在同一批 cache line 上）—— 退避不是可选项。
inline void backoff(unsigned& step) noexcept {
    if (step < 8) {
        // spin immediately
    } else if (step < 64) {
        cpu_relax();
    } else {
        std::this_thread::yield();
    }
    if (step < (1u << 20)) ++step;
}

// ---------------------------------------------------------------------------
// 低频通道：阶梯 + 阶梯走完后的睡眠
// ---------------------------------------------------------------------------
// 只给**消息速率远低于 10^5/s** 的循环用（秒级巡检、低频工具通道）。
// 热路径（报单 / 回报 / 行情）**绝对不要**用它 —— 见 backoff() 的注释。
//
// 为什么 step > 256 才开始睡：前 256 次空转覆盖"对端就在几微秒后发一条"
// 的常见情况，此时睡下去反而增加延迟；真正长时间无事可做时才让出 CPU，
// 免得在一个几乎没消息的通道上空烧一个核。
//
// ⚠️ 实测代价远大于字面的 20µs：`sleep_for` 走 `clock_nanosleep`，Linux 默认
// **timer slack 50µs**，且线程变成不可运行态、唤醒要重新排队（尾延迟差）。
// 所以它**只**适合"低频 + 不独占核"；独占核的热路径宁可烧核也不要睡眠。
inline void backoff_sleep(unsigned& step) noexcept {
    backoff(step);
    if (step > 256) {
        std::this_thread::sleep_for(std::chrono::microseconds(20));
    }
}

} // namespace spin
